// @ts-check
// src/spawn-task.js — Generate and update a child's SESSION_TASK.md
//
// Implements docs/SPAWN_PROTOCOL.md §4. The parent generates a forge-plan-style
// task file when it spawns a child; the child checks off subtasks and appends
// progress lines as it works; the parent reads it back to report progress.
//
// The file is gitignored and never meant to be committed.
'use strict';

const fs = require('fs');
const path = require('path');

const FILENAME = 'SESSION_TASK.md';
const GITIGNORE_ENTRY = 'SESSION_TASK.md';

function nowIso() {
  return new Date().toISOString();
}

function shortTime(d) {
  const date = d instanceof Date ? d : new Date(d || Date.now());
  if (isNaN(date.getTime())) return '--:--';
  return String(date.getHours()).padStart(2, '0') + ':' +
         String(date.getMinutes()).padStart(2, '0');
}

function oneLine(s) {
  return String(s == null ? '' : s).replace(/\s+/g, ' ').trim();
}

function taskFilePath(dir, explicitPath) {
  if (explicitPath) return path.resolve(explicitPath);
  return path.join(path.resolve(dir || process.cwd()), FILENAME);
}

/**
 * Resolve the PER-INSTANCE task-file path for a child. Each child MUST have
 * its own file, so multiple children in the same cwd never collide.
 *
 * Resolution order:
 *   1. explicit path (opts.taskFile)
 *   2. <sessionDir>/SESSION_TASK.md   (unique per instance — recommended)
 *   3. <dir>/<identifier>.SESSION_TASK.md  (fallback if no sessionDir)
 *
 * @param {Object} opts { taskFile?, sessionDir?, dir?, identifier? }
 * @returns {string}
 */
function instanceTaskPath(opts = {}) {
  if (opts.taskFile) return path.resolve(opts.taskFile);
  if (opts.sessionDir) return path.join(path.resolve(opts.sessionDir), FILENAME);
  const dir = path.resolve(opts.dir || process.cwd());
  const id = String(opts.identifier || opts.session || 'child')
    .replace(/[^A-Za-z0-9._-]/g, '-');
  return path.join(dir, id + '.' + FILENAME);
}

/**
 * Ensure SESSION_TASK.md is present in the project's .gitignore.
 * Best-effort; never throws.
 *
 * @returns {{ status: 'present'|'added'|'created'|'error', path: string }}
 */
function ensureGitignored(projectDir) {
  const dir = path.resolve(projectDir || process.cwd());
  const gi = path.join(dir, '.gitignore');
  try {
    if (!fs.existsSync(gi)) {
      fs.writeFileSync(gi, '# Added by Forge Agent\n' + GITIGNORE_ENTRY + '\n', 'utf8');
      return { status: 'created', path: gi };
    }
    const content = fs.readFileSync(gi, 'utf8');
    const lines = content.split(/\r?\n/).map(l => l.trim());
    if (lines.some(l => l === GITIGNORE_ENTRY || l === '/' + GITIGNORE_ENTRY)) {
      return { status: 'present', path: gi };
    }
    const sep = content.endsWith('\n') ? '' : '\n';
    fs.appendFileSync(gi, sep + '\n# Forge Agent child task (never commit)\n' + GITIGNORE_ENTRY + '\n', 'utf8');
    return { status: 'added', path: gi };
  } catch (e) {
    return { status: 'error', path: gi };
  }
}

/**
 * Render the markdown content for a child's task file.
 *
 * @param {Object} opts
 * @param {string} [opts.identifier]  full child id (defaults to 'forge-child')
 * @param {string} [opts.session]     child session name (defaults to identifier)
 * @param {string} [opts.parentId]  parent session name
 * @param {number} [opts.parentPid] parent pid
 * @param {string} [opts.role]      role label
 * @param {string} [opts.cwd]       working dir
 * @param {string} [opts.task]      assigned task
 * @param {string[]} [opts.subtasks] explicit subtasks (else derived from task)
 * @param {string} [opts.context]   handed-off context
 * @returns {string}
 */
function renderTaskFile(opts = {}) {
  const identifier = opts.identifier || 'forge-child';
  const session = opts.session || identifier;
  const parentId = opts.parentId || '-';
  const parentPid = opts.parentPid || '-';
  const role = opts.role || session;
  const cwd = opts.cwd || process.cwd();
  const task = oneLine(opts.task || '');
  const created = nowIso();

  // Subtasks: explicit list, else derive simple defaults from the task.
  let subtasks;
  if (Array.isArray(opts.subtasks) && opts.subtasks.length > 0) {
    subtasks = opts.subtasks.map(s => oneLine(s)).filter(Boolean);
  } else {
    subtasks = [
      'Read the assigned task and surrounding project context',
      'Plan the approach',
      'Implement the change',
      'Verify / test the change',
    ];
  }

  const lines = [];
  lines.push('<!-- AUTO-GENERATED by Forge Agent supervisor. Do not commit. -->');
  lines.push('# SESSION_TASK — ' + identifier);
  lines.push('');
  lines.push('- Session   : ' + session);
  lines.push('- Parent    : ' + parentId + ' (pid ' + parentPid + ')');
  lines.push('- Role      : ' + role);
  lines.push('- Created   : ' + created);
  lines.push('- Working   : ' + cwd);
  lines.push('');
  lines.push('## Assigned task');
  lines.push('');
  lines.push(task || '(none)');
  lines.push('');
  lines.push('## Subtasks');
  lines.push('');
  for (const s of subtasks) lines.push('- [ ] ' + s);
  lines.push('');
  lines.push('## Handed-off context');
  lines.push('');
  if (opts.context && String(opts.context).trim()) {
    for (const l of String(opts.context).split(/\r?\n/)) lines.push(oneLine(l));
  } else {
    lines.push('(none)');
  }
  lines.push('');
  lines.push('## Progress log');
  lines.push('');
  lines.push('- [' + shortTime() + '] spawned');
  lines.push('');
  return lines.join('\n');
}

/**
 * Write the child's task file to disk.
 *
 * @param {Object} [opts]
 * @param {string} [opts.taskFile]
 * @param {string} [opts.sessionDir]
 * @param {string} [opts.dir]
 * @param {string} [opts.cwd]
 * @param {string} [opts.identifier]
 * @param {string} [opts.session]
 * @param {string} [opts.role]
 * @param {number} [opts.parentPid]
 * @param {string} [opts.parentId]
 * @param {string} [opts.task]
 * @param {string[]} [opts.subtasks]
 * @param {string} [opts.context]
 * @returns {{ ok:boolean, path:string, error?:string }}
 */
function writeTaskFile(opts = {}) {
  const file = instanceTaskPath({
    taskFile: opts.taskFile,
    sessionDir: opts.sessionDir,
    dir: opts.dir || opts.cwd,
    identifier: opts.identifier || opts.session,
  });
  try {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, renderTaskFile(opts), 'utf8');
    // Only touch the repo .gitignore when the file actually lives in the
    // project dir. A per-instance file under the session dir is already
    // outside the repo and needs no ignore entry.
    const projectDir = path.resolve(opts.dir || opts.cwd || process.cwd());
    if (path.resolve(path.dirname(file)) === projectDir) {
      ensureGitignored(projectDir);
    }
    return { ok: true, path: file };
  } catch (e) {
    return { ok: false, path: file, error: e.message };
  }
}

/**
 * Remove a child's per-instance task file (cleanup at session end).
 * Best-effort; never throws.
 * @returns {{ ok:boolean, removed:boolean }}
 */
function cleanupTaskFile(filePath) {
  try {
    if (!filePath || !fs.existsSync(filePath)) return { ok: true, removed: false };
    fs.unlinkSync(filePath);
    return { ok: true, removed: true };
  } catch (_) {
    return { ok: false, removed: false };
  }
}

/** Read a child task file from disk (best-effort). */
function readTaskFile(filePath) {
  try {
    if (!filePath || !fs.existsSync(filePath)) return null;
    return fs.readFileSync(filePath, 'utf8');
  } catch (_) {
    return null;
  }
}

/**
 * Parse a task-file markdown into structured progress info.
 *
 * @returns {{ subtasks:{done:boolean,text:string}[], done:number, total:number,
 *             progress:string[], complete:boolean }}
 */
function parseTaskFile(content) {
  const result = { subtasks: [], done: 0, total: 0, progress: [], complete: false };
  if (!content) return result;
  const lines = String(content).split(/\r?\n/);
  let section = null;
  for (const raw of lines) {
    const line = raw.trim();
    if (/^##\s+Subtasks/i.test(line)) { section = 'subtasks'; continue; }
    if (/^##\s+Progress/i.test(line)) { section = 'progress'; continue; }
    if (/^##\s+/.test(line)) { section = null; continue; }
    if (section === 'subtasks') {
      const m = line.match(/^-\s*\[( |x|X)\]\s*(.*)$/);
      if (m) {
        const done = m[1].toLowerCase() === 'x';
        result.subtasks.push({ done, text: m[2] });
        result.total++;
        if (done) result.done++;
      }
    } else if (section === 'progress') {
      if (/^-\s*\[/.test(line)) result.progress.push(line);
      if (/TASK_COMPLETE/i.test(line)) result.complete = true;
    }
  }
  if (result.total > 0 && result.done === result.total) result.complete = true;
  return result;
}

/**
 * Mark a subtask done in a task file (used by the child, or by the parent to
 * record an externally-observed completion). Matches by substring.
 *
 * @returns {{ ok:boolean, changed:boolean }}
 */
function markSubtaskDone(filePath, matchText) {
  try {
    if (!fs.existsSync(filePath)) return { ok: false, changed: false };
    const text = fs.readFileSync(filePath, 'utf8');
    const needle = oneLine(matchText).toLowerCase();
    let changed = false;
    const out = text.split(/\r?\n/).map(line => {
      const m = line.match(/^(\s*-\s*)\[ \](\s*)(.*)$/);
      if (m && m[3].toLowerCase().includes(needle)) {
        changed = true;
        return m[1] + '[x]' + m[2] + m[3];
      }
      return line;
    }).join('\n');
    if (changed) fs.writeFileSync(filePath, out, 'utf8');
    return { ok: true, changed };
  } catch (_) {
    return { ok: false, changed: false };
  }
}

/** Append a progress-log line to a task file (used by the child). */
function appendProgress(filePath, text) {
  try {
    if (!fs.existsSync(filePath)) return { ok: false };
    const line = '- [' + shortTime() + '] ' + oneLine(text);
    fs.appendFileSync(filePath, line + '\n', 'utf8');
    return { ok: true, line };
  } catch (_) {
    return { ok: false };
  }
}

module.exports = {
  FILENAME,
  GITIGNORE_ENTRY,
  ensureGitignored,
  renderTaskFile,
  writeTaskFile,
  readTaskFile,
  parseTaskFile,
  markSubtaskDone,
  appendProgress,
  taskFilePath,
  instanceTaskPath,
  cleanupTaskFile,
};

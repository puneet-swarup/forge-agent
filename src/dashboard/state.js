// src/dashboard/state.js — a read-only snapshot of everything Forge Agent keeps.
//
// The dashboard runs in its OWN process, so it cannot see the in-memory
// registries that the agents it reports on hold (process-manager's Map, the
// supervisor's caches). Everything below is therefore read from FORGE_HOME:
//
//   <home>/instances/<session>.json          supervisor heartbeat records (SPAWN_PROTOCOL §5)
//   <home>/sessions/<name>/instance.json     legacy per-session record (same shape)
//   <home>/sessions/<name>/summary.json      per-run summary (src/run-summary.js)
//   <home>/sessions/<name>/SESSION_TASK.md   the child's assigned task (src/spawn-task.js)
//   <home>/history.json                      task history (src/history.js)
//   <home>/processes.json                    OPTIONAL background-process snapshot
//   <project>/.git/HEAD                      branch label for a project row
//
// Anything that is not on disk is reported as null — never guessed. Every
// reader is individually guarded: one unreadable file cannot take the snapshot
// down, and a corrupt history.json yields empty arrays instead of throwing.
'use strict';

const fs = require('fs');
const path = require('path');

// ─────────────────────────────────────────────
//  Small, defensive coercion helpers
// ─────────────────────────────────────────────

/** A non-empty string, or null. */
function str(v) {
  return typeof v === 'string' && v.trim() !== '' ? v : null;
}

/** A finite number, or null. Accepts numeric strings (registry files vary). */
function numberOrNull(v) {
  if (typeof v === 'number' && Number.isFinite(v)) return v;
  if (typeof v === 'string' && v.trim() !== '') {
    const n = Number(v);
    if (Number.isFinite(n)) return n;
  }
  return null;
}

/** An ISO-8601 string, or null. Accepts epoch-ms numbers and date strings. */
function toIso(v) {
  if (v === null || v === undefined || v === '') return null;
  let d;
  if (typeof v === 'number') {
    if (!Number.isFinite(v)) return null;
    d = new Date(v);
  } else if (typeof v === 'string') {
    d = new Date(v);
  } else {
    return null;
  }
  const t = d.getTime();
  return Number.isNaN(t) ? null : d.toISOString();
}

/** A list of file paths, or null when the field is absent. */
function stringList(v) {
  if (!Array.isArray(v)) return null;
  return v.filter((x) => typeof x === 'string');
}

/** Read + parse JSON; null on any failure (missing, unreadable, corrupt). */
function readJsonFile(file) {
  try {
    return JSON.parse(fs.readFileSync(file, 'utf8'));
  } catch (_) {
    return null;
  }
}

/** Is this PID alive on this host? EPERM means "alive but not ours". */
function isPidAlive(pid) {
  if (!pid || typeof pid !== 'number') return false;
  try {
    process.kill(pid, 0);
    return true;
  } catch (err) {
    return !!(err && err.code === 'EPERM');
  }
}

/** Heartbeat TTL, mirroring src/session-registry.js (§5.1). */
function heartbeatTtlMs() {
  const v = parseInt(process.env.FORGE_HEARTBEAT_TTL_MS, 10);
  return Number.isFinite(v) && v > 0 ? v : 20000;
}

/**
 * Liveness/status for a registry record, mirroring
 * session-registry.classifyInstance: a dead PID wins, then a stale heartbeat
 * means 'unresponsive', otherwise the record's own status stands.
 */
function classify(record, alive, now) {
  if (!alive) return 'dead';
  const beat = numberOrNull(record.lastHeartbeat) || numberOrNull(record.startedAt);
  if (!beat) return str(record.status) || 'running';
  if (now - beat > heartbeatTtlMs()) return 'unresponsive';
  return str(record.status) || 'running';
}

// ─────────────────────────────────────────────
//  Directory helpers
// ─────────────────────────────────────────────

function subDirs(dir) {
  try {
    return fs.readdirSync(dir, { withFileTypes: true })
      .filter((d) => d.isDirectory())
      .map((d) => path.join(dir, d.name))
      .sort();
  } catch (_) {
    return [];
  }
}

function jsonFiles(dir) {
  try {
    return fs.readdirSync(dir, { withFileTypes: true })
      .filter((d) => d.isFile() && d.name.endsWith('.json'))
      .map((d) => path.join(dir, d.name))
      .sort();
  } catch (_) {
    return [];
  }
}

function readText(file) {
  try {
    return fs.readFileSync(file, 'utf8');
  } catch (_) {
    return null;
  }
}

// ─────────────────────────────────────────────
//  Task text: SESSION_TASK.md → summary.json → record
// ─────────────────────────────────────────────

/**
 * Pull the assigned task out of a child's SESSION_TASK.md.
 * The file is generated by src/spawn-task.js with a "## Assigned task"
 * section that runs until the next "## " heading.
 */
function taskFromTaskFile(dir) {
  const text = readText(path.join(dir, 'SESSION_TASK.md'));
  if (!text) return null;
  const lines = text.split(/\r?\n/);
  let inSection = false;
  const body = [];
  for (const line of lines) {
    if (/^##\s+Assigned task\s*$/i.test(line.trim())) { inSection = true; continue; }
    if (inSection && /^##\s+/.test(line)) break;
    if (inSection) body.push(line);
  }
  const joined = body.join('\n').trim();
  if (!joined || joined === '(none)') return null;
  return joined;
}

function taskFor(sessionDir, record) {
  const summary = readJsonFile(path.join(sessionDir, 'summary.json'));
  const fromSummary = summary && str(summary.task);
  if (fromSummary && fromSummary !== '(unknown)') return fromSummary;
  return taskFromTaskFile(sessionDir) || str(record && record.task) || fromSummary || null;
}

// ─────────────────────────────────────────────
//  Agents — supervisor registry records
// ─────────────────────────────────────────────

function readAgents(home, now) {
  const byId = new Map();

  // 1) Canonical heartbeat files: always written, whatever --session-dir says.
  for (const file of jsonFiles(path.join(home, 'instances'))) {
    const rec = readJsonFile(file);
    if (!rec || typeof rec !== 'object' || Array.isArray(rec)) continue;
    const id = str(rec.id) || str(rec.name) || path.basename(file, '.json');
    if (!byId.has(id)) byId.set(id, rec);
  }

  // 2) Legacy per-session copies, only when the canonical file is missing.
  for (const dir of subDirs(path.join(home, 'sessions'))) {
    const rec = readJsonFile(path.join(dir, 'instance.json'));
    if (!rec || typeof rec !== 'object' || Array.isArray(rec)) continue;
    const id = str(rec.id) || str(rec.name) || path.basename(dir);
    if (!byId.has(id)) byId.set(id, rec);
  }

  const agents = [];
  for (const [key, rec] of byId) {
    const pid = numberOrNull(rec.pid);
    const alive = isPidAlive(pid);
    const sessionDir = str(rec.sessionDir) || path.join(home, 'sessions', key);
    agents.push({
      id: str(rec.identifier) || key,
      pid,
      status: classify(rec, alive, now),
      session: str(rec.id) || str(rec.name) || key,
      task: taskFor(sessionDir, rec),
      startedAt: toIso(rec.startedAt),
      lastHeartbeat: toIso(rec.lastHeartbeat),
      workingDir: str(rec.cwd),
      alive,
    });
  }

  agents.sort((a, b) => String(b.startedAt || '').localeCompare(String(a.startedAt || '')));
  return agents;
}

// ─────────────────────────────────────────────
//  Sessions — one directory per session under <home>/sessions
// ─────────────────────────────────────────────

/**
 * Internal session records: the public shape plus workingDir/finishedAt, which
 * the project roll-up needs but the snapshot does not expose.
 */
function readSessionRecords(home) {
  return subDirs(path.join(home, 'sessions')).map((dir) => {
    const summary = readJsonFile(path.join(dir, 'summary.json')) || {};
    const inst = readJsonFile(path.join(dir, 'instance.json')) || {};
    const finishedAt = toIso(summary.finishedAt);
    const durationMs = numberOrNull(summary.durationMs);
    // summary.json records when a run ENDED; the registry record knows when the
    // session STARTED. Fall back to finishedAt - durationMs before giving up.
    let startedAt = toIso(inst.startedAt) || toIso(summary.startedAt);
    if (!startedAt && finishedAt && durationMs !== null) {
      startedAt = toIso(new Date(new Date(finishedAt).getTime() - durationMs));
    }
    return {
      name: path.basename(dir),
      task: str(summary.task) || taskFromTaskFile(dir) || str(inst.task) || null,
      status: str(summary.status) || str(inst.status) || null,
      startedAt,
      filesWritten: stringList(summary.filesWritten),
      dir,
      workingDir: str(summary.workingDir) || str(inst.cwd),
      finishedAt,
    };
  }).sort((a, b) => String(b.startedAt || '').localeCompare(String(a.startedAt || '')));
}

function publicSession(rec) {
  return {
    name: rec.name,
    task: rec.task,
    status: rec.status,
    startedAt: rec.startedAt,
    filesWritten: rec.filesWritten,
    dir: rec.dir,
  };
}

// ─────────────────────────────────────────────
//  Tasks — history.json
// ─────────────────────────────────────────────

/** history.json entries, newest first. A corrupt file yields []. */
function readHistoryEntries(home) {
  const parsed = readJsonFile(path.join(home, 'history.json'));
  const entries = parsed && Array.isArray(parsed.entries)
    ? parsed.entries
    : (Array.isArray(parsed) ? parsed : []);
  return entries.filter((e) => e && typeof e === 'object' && !Array.isArray(e));
}

/** Normalise a verification value (string | bool | object) to text or null. */
function verificationText(v) {
  if (v === null || v === undefined) return null;
  if (typeof v === 'string') return v.trim() === '' ? null : v;
  if (typeof v === 'boolean' || typeof v === 'number') return String(v);
  try { return JSON.stringify(v); } catch (_) { return null; }
}

function readTasks(entries) {
  return entries.map((e) => ({
    task: str(e.task) || str(e.taskShort),
    status: str(e.status),
    model: str(e.model),
    profile: str(e.profile),
    durationMs: numberOrNull(e.durationMs),
    steps: numberOrNull(e.stepsCount),
    // history.js stamps `timestamp` when the entry is written, i.e. at the end
    // of the run; `finishedAt` wins when a record carries one explicitly.
    finishedAt: toIso(e.finishedAt) || toIso(e.timestamp),
    filesWritten: stringList(e.filesWritten),
    verification: verificationText(e.verification),
  }));
}

// ─────────────────────────────────────────────
//  Projects — rolled up from working directories
// ─────────────────────────────────────────────

/**
 * Branch name from <dir>/.git/HEAD. Handles a worktree/submodule, where .git
 * is a file containing "gitdir: <path>". Returns null when there is no repo.
 */
function gitBranchFor(dir) {
  try {
    const dotGit = path.join(dir, '.git');
    let gitDir = dotGit;
    let stat;
    try { stat = fs.statSync(dotGit); } catch (_) { return null; }
    if (!stat.isDirectory()) {
      const text = readText(dotGit);
      if (!text) return null;
      const m = text.match(/^gitdir:\s*(.+)$/m);
      if (!m) return null;
      gitDir = path.resolve(dir, m[1].trim());
    }
    const head = readText(path.join(gitDir, 'HEAD'));
    if (!head) return null;
    const ref = head.match(/^ref:\s*refs\/heads\/(.+)$/m);
    if (ref) return ref[1].trim() || null;
    const sha = head.trim();
    if (/^[0-9a-f]{40}$/i.test(sha)) return sha.slice(0, 7); // detached HEAD
    return null;
  } catch (_) {
    return null;
  }
}

function readProjects(home, entries, sessions) {
  /** @type {Map<string, {last:string|null, sessions:number}>} */
  const byPath = new Map();

  const bucket = (p) => {
    if (!byPath.has(p)) byPath.set(p, { last: null, sessions: 0 });
    return byPath.get(p);
  };
  // A directory with no timestamps is still a project — record it, just with
  // lastActivity null rather than dropping the row.
  const touch = (p, iso) => {
    const b = bucket(p);
    if (iso && (!b.last || iso > b.last)) b.last = iso;
    return b;
  };

  for (const e of entries) {
    const dir = str(e.workingDir);
    if (!dir) continue;
    let abs;
    try { abs = path.resolve(dir); } catch (_) { continue; }
    touch(abs, toIso(e.timestamp) || toIso(e.finishedAt));
  }

  for (const s of sessions) {
    const dir = s.workingDir;
    if (!dir) continue;
    let abs;
    try { abs = path.resolve(dir); } catch (_) { continue; }
    const b = touch(abs, s.finishedAt || s.startedAt);
    b.sessions += 1;
  }

  const projects = [];
  for (const [p, info] of byPath) {
    projects.push({
      path: p,
      name: path.basename(p) || p,
      lastActivity: info.last,
      gitBranch: gitBranchFor(p),
      sessionCount: info.sessions,
    });
  }
  projects.sort((a, b) => String(b.lastActivity || '').localeCompare(String(a.lastActivity || '')));
  return projects;
}

// ─────────────────────────────────────────────
//  Processes — background child processes
// ─────────────────────────────────────────────

function uptimeOf(entry, now) {
  const explicit = numberOrNull(entry.uptimeMs);
  if (explicit !== null) return Math.max(0, explicit);
  const startedAt = numberOrNull(entry.startedAt);
  if (startedAt === null) return null;
  return Math.max(0, now - startedAt);
}

/**
 * Background processes have NO on-disk registry: src/process-manager.js keeps
 * them in a module-level Map, which a separate dashboard process cannot see.
 * So we read an optional <home>/processes.json snapshot first (a file another
 * Forge process may write), then fall back to the in-process Map, which is only
 * populated when the dashboard happens to run inside the agent process.
 */
function readProcesses(home, now) {
  const out = [];
  const seen = new Set();

  const push = (name, entry) => {
    if (!name || seen.has(name)) return;
    seen.add(name);
    out.push({
      name,
      pid: numberOrNull(entry.pid),
      status: str(entry.status),
      uptimeMs: entry.status === 'running' || entry.status === 'starting' ? uptimeOf(entry, now) : null,
      command: str(entry.command),
    });
  };

  const disk = readJsonFile(path.join(home, 'processes.json'));
  const list = Array.isArray(disk) ? disk : (disk && Array.isArray(disk.processes) ? disk.processes : []);
  for (const p of list) {
    if (p && typeof p === 'object' && !Array.isArray(p)) push(str(p.name), p);
  }

  try {
    const pm = require('../process-manager');
    const registry = pm && pm.REGISTRY;
    if (registry && typeof registry.forEach === 'function') {
      registry.forEach((entry, name) => {
        if (entry && typeof entry === 'object') push(name, entry);
      });
    }
  } catch (_) { /* process-manager unavailable: nothing to add */ }

  return out;
}

// ─────────────────────────────────────────────
//  Public API
// ─────────────────────────────────────────────

function resolveHome(forgeHome) {
  if (forgeHome) return path.resolve(forgeHome);
  try {
    return require('../paths').forgeHome();
  } catch (_) {
    return path.resolve(process.cwd());
  }
}

/**
 * Collect the whole dashboard snapshot from disk.
 *
 * @param {Object} [opts]
 * @param {string} [opts.forgeHome]  root to read (default: ~/.forge-agent)
 * @returns {{
 *   generatedAt: string, forgeHome: string,
 *   agents: Array<Object>, sessions: Array<Object>, projects: Array<Object>,
 *   tasks: Array<Object>, processes: Array<Object>
 * }}
 */
function collectState(opts = {}) {
  const home = resolveHome(opts && opts.forgeHome);
  const now = Date.now();
  const snapshot = {
    generatedAt: new Date(now).toISOString(),
    forgeHome: home,
    agents: [],
    sessions: [],
    projects: [],
    tasks: [],
    processes: [],
  };

  // Each reader is independently guarded, so a single bad directory degrades
  // one section instead of the whole snapshot.
  try { snapshot.agents = readAgents(home, now); } catch (_) { snapshot.agents = []; }
  let sessionRecords = [];
  try { sessionRecords = readSessionRecords(home); } catch (_) { sessionRecords = []; }
  try { snapshot.sessions = sessionRecords.map(publicSession); } catch (_) { snapshot.sessions = []; }
  let entries = [];
  try { entries = readHistoryEntries(home); } catch (_) { entries = []; }
  try { snapshot.tasks = readTasks(entries); } catch (_) { snapshot.tasks = []; }
  try { snapshot.projects = readProjects(home, entries, sessionRecords); } catch (_) { snapshot.projects = []; }
  try { snapshot.processes = readProcesses(home, now); } catch (_) { snapshot.processes = []; }

  return snapshot;
}


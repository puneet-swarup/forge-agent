// src/lifecycle.js — mandatory project artifacts and their lifecycle contract.
//
// Every Forge project has a fixed set of markdown artifacts. Each artifact has
// exactly ONE owner, ONE purpose, and a defined phase in the task lifecycle.
// This module is the single source of truth for those rules: the system prompt
// renders its table, and scripts/lifecycle.js enforces it at task start and at
// TASK_COMPLETE time.
'use strict';

const ARTIFACTS = [
  {
    file: 'FORGE_PLAN.md',
    owner: 'agent',
    phase: 'created',
    purpose: 'Your own step-by-step plan for the CURRENT task. Written before executing.',
    lifecycle: 'Created at task start, ticked per step, deleted at sign-off.',
    requiredAtStart: true,
    mustBeCompleteAtEnd: true,
  },
  {
    file: 'FORGE_TODO.md',
    owner: 'human',
    phase: 'ongoing',
    purpose: 'The durable backlog across sessions.',
    lifecycle: 'Human-authored; the agent may tick items done but never adds product ideas.',
    requiredAtStart: false,
    mustBeCompleteAtEnd: false,
  },
  {
    file: 'SESSION_CONTEXT.md',
    owner: 'agent',
    phase: 'ongoing',
    purpose: 'Ephemeral working memory: task, progress, current state.',
    lifecycle: 'Auto-generated and regenerated by the framework; never hand-edited.',
    requiredAtStart: false,
    mustBeCompleteAtEnd: false,
  },
  {
    file: 'PENDING_WORK.md',
    owner: 'human',
    phase: 'ongoing',
    purpose: 'Narrative backlog of deferred decisions.',
    lifecycle: 'Human-maintained; read for context, never rewritten by the agent.',
    requiredAtStart: false,
    mustBeCompleteAtEnd: false,
  },
  {
    file: 'ARCHITECTURE.md',
    owner: 'agent',
    phase: 'ongoing',
    purpose: 'The as-built map of the system.',
    lifecycle: 'Updated only when a module boundary or tool protocol actually changed.',
    requiredAtStart: false,
    mustBeCompleteAtEnd: false,
  },
];

/** Look up an artifact descriptor by file name. */
function getArtifact(file) {
  return ARTIFACTS.find(a => a.file === file) || null;
}

/** Files the agent must create before executing a multi-step task. */
function requiredAtStart() {
  return ARTIFACTS.filter(a => a.requiredAtStart).map(a => a.file);
}

/** Files that must have no open checkbox items at TASK_COMPLETE. */
function requiredCompleteAtEnd() {
  return ARTIFACTS.filter(a => a.mustBeCompleteAtEnd).map(a => a.file);
}

/**
 * Render the artifact table used inside the system prompt.
 * Kept pure so the prompt and the docs can never drift.
 */
function renderArtifactTable() {
  const width = Math.max(...ARTIFACTS.map(a => a.file.length)) + 2;
  return ARTIFACTS.map(function (a) {
    const name = a.file.padEnd(width, ' ');
    return '  ' + name + '[' + a.owner + '] ' + a.purpose + '\n' +
      '  ' + ' '.repeat(width) + a.lifecycle;
  }).join('\n');
}

module.exports = {
  ARTIFACTS,
  getArtifact,
  requiredAtStart,
  requiredCompleteAtEnd,
  renderArtifactTable,
};

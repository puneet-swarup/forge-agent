// tests/dashboard/state.test.js — the dashboard snapshot is a pure read of disk.
//
// These tests build a fake forge home by hand: a history.json, a supervisor
// registry, two session dirs and a project with a git HEAD. Nothing here starts
// a server or an agent — collectState() must be safe to call at any moment, and
// must degrade to empty arrays / nulls rather than throwing.
'use strict';

const fs = require('fs');
const os = require('os');
const path = require('path');

const { collectState, gitBranchFor } = require('../../src/dashboard/state');

// A PID that cannot be running: Linux caps pids far below this.
const DEAD_PID = 2147483647;

const AGENT_KEYS = [
  'alive', 'id', 'lastHeartbeat', 'pid', 'session', 'startedAt', 'status', 'task', 'workingDir',
];
const SESSION_KEYS = ['dir', 'filesWritten', 'name', 'startedAt', 'status', 'task'];
const PROJECT_KEYS = ['gitBranch', 'lastActivity', 'name', 'path', 'sessionCount'];
const TASK_KEYS = [
  'durationMs', 'filesWritten', 'finishedAt', 'model', 'profile', 'status', 'steps', 'task', 'verification',
];
const PROCESS_KEYS = ['command', 'name', 'pid', 'status', 'uptimeMs'];

const START_MS = Date.UTC(2026, 10, 20, 9, 0, 0); // 2026-11-20T09:00:00Z

function writeJson(file, value) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, JSON.stringify(value, null, 2), 'utf8');
}

function writeText(file, value) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, value, 'utf8');
}

/** A child's SESSION_TASK.md, in the exact shape src/spawn-task.js renders. */
function taskFile(identifier, session, task) {
  return [
    '<!-- AUTO-GENERATED by Forge Agent supervisor. Do not commit. -->',
    '# SESSION_TASK — ' + identifier,
    '',
    '- Session   : ' + session,
    '- Parent    : brave-otter-9f3a (pid 39800)',
    '- Role      : ' + session,
    '- Created   : 2026-11-20T09:00:00.000Z',
    '- Working   : /tmp/proj',
    '',
    '## Assigned task',
    '',
    task,
    '',
    '## Subtasks',
    '',
    '- [ ] Read the assigned task and surrounding project context',
    '- [ ] Implement the change',
    '',
    '## Handed-off context',
    '',
    '(none)',
    '',
    '## Progress log',
    '',
    '- [09:00] spawned',
    '',
  ].join('\n');
}

/**
 * A populated forge home.
 *   proj/alpha  — a git repo on branch `main`, used by sess-one + one history entry
 *   proj/beta   — no .git at all, used by one history entry
 */
function buildHome() {
  const home = fs.mkdtempSync(path.join(os.tmpdir(), 'forge-dash-state-'));
  const alpha = path.join(home, 'proj', 'alpha');
  const beta = path.join(home, 'proj', 'beta');

  writeText(path.join(alpha, '.git', 'HEAD'), 'ref: refs/heads/main\n');
  fs.mkdirSync(beta, { recursive: true });

  // ── history.json: two finished runs, one of them sparse ────────────────
  writeJson(path.join(home, 'history.json'), {
    version: 1,
    entries: [
      {
        id: 'h1',
        timestamp: '2026-11-20T10:30:00.000Z',
        task: 'Add the dashboard state collector',
        taskShort: 'Add the dashboard state collector',
        workingDir: alpha,
        model: 'deepseek',
        profile: 'default',
        session: 'sess-one',
        status: 'completed',
        durationMs: 125000,
        stepsCount: 17,
        filesWritten: ['src/dashboard/state.js', 'tests/dashboard/state.test.js'],
        verification: 'npm test',
      },
      {
        id: 'h2',
        timestamp: '2026-11-19T08:00:00.000Z',
        task: 'Fix a typo',
        workingDir: beta,
        status: 'failed',
        durationMs: 4000,
      },
    ],
  });

  // ── supervisor registry: one live, one dead, one barely-written ────────
  writeJson(path.join(home, 'instances', 'worker-live.json'), {
    id: 'worker-live',
    name: 'worker-live',
    identifier: 'forge-worker-live-' + process.pid,
    pid: process.pid,
    isChild: true,
    cwd: alpha,
    status: 'running',
    startedAt: Date.now() - 60000,
    lastHeartbeat: Date.now(),
    sessionDir: path.join(home, 'sessions', 'sess-one'),
  });
  writeJson(path.join(home, 'instances', 'worker-dead.json'), {
    id: 'worker-dead',
    name: 'worker-dead',
    identifier: 'forge-worker-dead-' + DEAD_PID,
    pid: DEAD_PID,
    isChild: true,
    cwd: beta,
    status: 'running', // stale: the PID is gone, so this must read as dead
    startedAt: START_MS,
    lastHeartbeat: START_MS,
    sessionDir: path.join(home, 'sessions', 'sess-two'),
  });
  // Deliberately incomplete record: no pid, no cwd, no timestamps.
  writeJson(path.join(home, 'instances', 'worker-bare.json'), {
    id: 'worker-bare',
    status: 'starting',
  });

  // ── sessions/sess-one: a finished run with a summary + task file ───────
  const sessOne = path.join(home, 'sessions', 'sess-one');
  writeText(path.join(sessOne, 'SESSION_TASK.md'),
    taskFile('forge-worker-live-' + process.pid, 'sess-one', 'Add the dashboard state collector'));
  writeJson(path.join(sessOne, 'summary.json'), {
    session: 'sess-one',
    role: 'sess-one',
    task: 'Add the dashboard state collector',
    status: 'completed',
    model: 'deepseek',
    profile: 'default',
    workingDir: alpha,
    durationMs: 125000,
    steps: 17,
    filesWritten: ['src/dashboard/state.js', 'tests/dashboard/state.test.js'],
    verification: 'npm test',
    finishedAt: '2026-11-20T10:30:00.000Z',
  });
  writeJson(path.join(sessOne, 'instance.json'), {
    id: 'sess-one',
    name: 'sess-one',
    identifier: 'forge-sess-one-' + DEAD_PID,
    pid: DEAD_PID,
    cwd: alpha,
    status: 'completed',
    startedAt: START_MS,
    lastHeartbeat: START_MS,
    sessionDir: sessOne,
  });

  // ── sessions/sess-two: a directory with nothing readable in it ─────────
  fs.mkdirSync(path.join(home, 'sessions', 'sess-two'), { recursive: true });

  // ── an optional background-process snapshot ────────────────────────────
  writeJson(path.join(home, 'processes.json'), {
    processes: [
      {
        name: 'dev-server',
        pid: 4242,
        status: 'running',
        startedAt: Date.now() - 5000,
        command: 'npm run dev',
      },
    ],
  });

  return { home, alpha, beta };
}

describe('collectState — snapshot shape', () => {
  let ctx;
  let state;

  beforeAll(() => {
    ctx = buildHome();
    state = collectState({ forgeHome: ctx.home });
  });

  afterAll(() => {
    try { fs.rmSync(ctx.home, { recursive: true, force: true }); } catch (_) {}
  });

  test('returns exactly the documented top-level keys', () => {
    expect(Object.keys(state).sort()).toEqual(
      ['agents', 'forgeHome', 'generatedAt', 'processes', 'projects', 'sessions', 'tasks']);
  });

  test('generatedAt is an ISO timestamp and forgeHome is the home it read', () => {
    expect(typeof state.generatedAt).toBe('string');
    expect(new Date(state.generatedAt).toISOString()).toBe(state.generatedAt);
    expect(state.forgeHome).toBe(path.resolve(ctx.home));
  });

  test('every section is an array', () => {
    for (const key of ['agents', 'sessions', 'projects', 'tasks', 'processes']) {
      expect(Array.isArray(state[key])).toBe(true);
    }
  });

  test('agents carry the documented keys and nothing else', () => {
    expect(state.agents.length).toBe(4); // live, dead, bare + the legacy sess-one record
    for (const agent of state.agents) {
      expect(Object.keys(agent).sort()).toEqual(AGENT_KEYS);
    }
  });

  test('a live agent is alive, with its identifier, pid and heartbeat', () => {
    const live = state.agents.find((a) => a.session === 'worker-live');
    expect(live).toBeTruthy();
    expect(live.id).toBe('forge-worker-live-' + process.pid);
    expect(live.pid).toBe(process.pid);
    expect(live.alive).toBe(true);
    expect(live.status).toBe('running');
    expect(live.workingDir).toBe(path.resolve(ctx.alpha));
    expect(live.startedAt).toBe(new Date(live.startedAt).toISOString());
    expect(live.lastHeartbeat).toBe(new Date(live.lastHeartbeat).toISOString());
  });

  test('a record whose PID is gone reads as dead, whatever its status field says', () => {
    const dead = state.agents.find((a) => a.session === 'worker-dead');
    expect(dead.alive).toBe(false);
    expect(dead.status).toBe('dead');
  });

  test('missing registry fields become null, never a guess', () => {
    const bare = state.agents.find((a) => a.session === 'worker-bare');
    expect(bare).toBeTruthy();
    expect(bare.pid).toBe(null);
    expect(bare.alive).toBe(false);
    expect(bare.startedAt).toBe(null);
    expect(bare.lastHeartbeat).toBe(null);
    expect(bare.workingDir).toBe(null);
    expect(bare.task).toBe(null);
    expect(bare.id).toBe('worker-bare'); // no identifier: falls back to the record id
  });

  test('an agent task is read from its SESSION_TASK.md', () => {
    const one = state.agents.find((a) => a.session === 'sess-one');
    expect(one.task).toBe('Add the dashboard state collector');
  });

  test('sessions carry the documented keys', () => {
    expect(state.sessions.length).toBe(2);
    for (const session of state.sessions) {
      expect(Object.keys(session).sort()).toEqual(SESSION_KEYS);
    }
  });

  test('a session with a summary reports task, status, files and a derived start', () => {
    const one = state.sessions.find((s) => s.name === 'sess-one');
    expect(one.task).toBe('Add the dashboard state collector');
    expect(one.status).toBe('completed');
    expect(one.filesWritten).toEqual([
      'src/dashboard/state.js',
      'tests/dashboard/state.test.js',
    ]);
    expect(one.startedAt).toBe(new Date(START_MS).toISOString());
    expect(one.dir).toBe(path.join(path.resolve(ctx.home), 'sessions', 'sess-one'));
  });

  test('a session dir with no summary is all nulls except its name and dir', () => {
    const two = state.sessions.find((s) => s.name === 'sess-two');
    expect(two).toBeTruthy();
    expect(two.task).toBe(null);
    expect(two.status).toBe(null);
    expect(two.startedAt).toBe(null);
    expect(two.filesWritten).toBe(null);
    expect(two.dir).toBe(path.join(path.resolve(ctx.home), 'sessions', 'sess-two'));
  });

  test('projects roll up working directories with branch and session count', () => {
    expect(state.projects.length).toBe(2);
    for (const project of state.projects) {
      expect(Object.keys(project).sort()).toEqual(PROJECT_KEYS);
    }
    const alpha = state.projects.find((p) => p.path === path.resolve(ctx.alpha));
    expect(alpha.name).toBe('alpha');
    expect(alpha.gitBranch).toBe('main');
    expect(alpha.sessionCount).toBe(1);
    expect(alpha.lastActivity).toBe('2026-11-20T10:30:00.000Z');

    const beta = state.projects.find((p) => p.path === path.resolve(ctx.beta));
    expect(beta.name).toBe('beta');
    expect(beta.gitBranch).toBe(null); // no .git — not invented
    expect(beta.sessionCount).toBe(0);
  });

  test('tasks mirror history.json, with nulls where the entry is sparse', () => {
    expect(state.tasks.length).toBe(2);
    for (const task of state.tasks) {
      expect(Object.keys(task).sort()).toEqual(TASK_KEYS);
    }
    const full = state.tasks[0];
    expect(full.task).toBe('Add the dashboard state collector');
    expect(full.status).toBe('completed');
    expect(full.model).toBe('deepseek');
    expect(full.profile).toBe('default');
    expect(full.durationMs).toBe(125000);
    expect(full.steps).toBe(17);
    expect(full.filesWritten.length).toBe(2);
    expect(full.verification).toBe('npm test');
    // history.js stamps `timestamp` when the run finishes.
    expect(full.finishedAt).toBe('2026-11-20T10:30:00.000Z');

    const sparse = state.tasks[1];
    expect(sparse.model).toBe(null);
    expect(sparse.profile).toBe(null);
    expect(sparse.steps).toBe(null);
    expect(sparse.filesWritten).toBe(null);
    expect(sparse.verification).toBe(null);
    expect(sparse.durationMs).toBe(4000);
  });

  test('processes come from the on-disk snapshot, with uptime', () => {
    expect(state.processes.length).toBe(1);
    const dev = state.processes[0];
    expect(Object.keys(dev).sort()).toEqual(PROCESS_KEYS);
    expect(dev.name).toBe('dev-server');
    expect(dev.pid).toBe(4242);
    expect(dev.status).toBe('running');
    expect(dev.command).toBe('npm run dev');
    expect(dev.uptimeMs).toBeGreaterThanOrEqual(5000);
  });

  test('the snapshot is JSON-serialisable (it is served as JSON)', () => {
    expect(() => JSON.parse(JSON.stringify(state))).not.toThrow();
  });
});

describe('collectState — degraded inputs', () => {
  test('a corrupt history.json yields empty arrays instead of throwing', () => {
    const home = fs.mkdtempSync(path.join(os.tmpdir(), 'forge-dash-corrupt-'));
    try {
      writeText(path.join(home, 'history.json'), '{"version":1,"entries":[ this is not json');
      writeJson(path.join(home, 'instances', 'kid.json'), {
        id: 'kid', identifier: 'forge-kid-1', pid: DEAD_PID, status: 'running',
        startedAt: START_MS, lastHeartbeat: START_MS,
      });

      let state;
      expect(() => { state = collectState({ forgeHome: home }); }).not.toThrow();
      expect(state.tasks).toEqual([]);
      expect(state.projects).toEqual([]);
      expect(state.sessions).toEqual([]);
      // The rest of the snapshot still works.
      expect(state.agents.length).toBe(1);
      expect(state.agents[0].session).toBe('kid');
    } finally {
      try { fs.rmSync(home, { recursive: true, force: true }); } catch (_) {}
    }
  });

  test('an empty forge home is empty, not an error', () => {
    const home = fs.mkdtempSync(path.join(os.tmpdir(), 'forge-dash-empty-'));
    try {
      const state = collectState({ forgeHome: home });
      expect(state.agents).toEqual([]);
      expect(state.sessions).toEqual([]);
      expect(state.projects).toEqual([]);
      expect(state.tasks).toEqual([]);
      expect(state.processes).toEqual([]);
      expect(state.forgeHome).toBe(path.resolve(home));
    } finally {
      try { fs.rmSync(home, { recursive: true, force: true }); } catch (_) {}
    }
  });

  test('a forge home that does not exist at all is empty, not an error', () => {
    const missing = path.join(os.tmpdir(), 'forge-dash-absent-' + Date.now());
    const state = collectState({ forgeHome: missing });
    expect(state.agents).toEqual([]);
    expect(state.sessions).toEqual([]);
    expect(state.projects).toEqual([]);
    expect(state.tasks).toEqual([]);
    expect(state.processes).toEqual([]);
  });

  test('a history.json that is a bare array is still understood', () => {
    const home = fs.mkdtempSync(path.join(os.tmpdir(), 'forge-dash-array-'));
    try {
      writeJson(path.join(home, 'history.json'), [
        { task: 'bare entry', status: 'partial', workingDir: path.join(home, 'p') },
      ]);
      const state = collectState({ forgeHome: home });
      expect(state.tasks.length).toBe(1);
      expect(state.tasks[0].task).toBe('bare entry');
      expect(state.projects.length).toBe(1);
      expect(state.projects[0].name).toBe('p');
    } finally {
      try { fs.rmSync(home, { recursive: true, force: true }); } catch (_) {}
    }
  });
});

describe('gitBranchFor', () => {
  test('reads a branch ref from .git/HEAD', () => {
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'forge-dash-git-'));
    try {
      writeText(path.join(dir, '.git', 'HEAD'), 'ref: refs/heads/feature/dashboard\n');
      expect(gitBranchFor(dir)).toBe('feature/dashboard');
    } finally {
      try { fs.rmSync(dir, { recursive: true, force: true }); } catch (_) {}
    }
  });

  test('shortens a detached HEAD to a 7-character sha', () => {
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'forge-dash-git-'));
    try {
      const sha = 'a'.repeat(40);
      writeText(path.join(dir, '.git', 'HEAD'), sha + '\n');
      expect(gitBranchFor(dir)).toBe('aaaaaaa');
    } finally {
      try { fs.rmSync(dir, { recursive: true, force: true }); } catch (_) {}
    }
  });

  test('returns null when there is no repository', () => {
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'forge-dash-nogit-'));
    try {
      expect(gitBranchFor(dir)).toBe(null);
      expect(gitBranchFor(path.join(dir, 'nope'))).toBe(null);
    } finally {
      try { fs.rmSync(dir, { recursive: true, force: true }); } catch (_) {}
    }
  });
});
